static inline bool UKASCII(unsigned c, uint8_t *key, uint8_t *mod) {
  *mod=0; *key=0;
  if(c>='a'&&c<='z') *key=c-'a'+4;
  else if(c>='A'&&c<='Z') { *key=c-'A'+4; *mod=2; }
  else if(c>='1'&&c<='9') *key=c-'1'+0x1e;
  else if(c=='0') *key=0x27;
  else if(c=='\n'||c=='\r') *key=0x28;
  else if(c=='\b') *key=0x2a;
  else if(c=='\t') *key=0x2b;
  else {
    const char *plain=" -=[]\\;'/`,.";
    const uint8_t codes[]={0x2c,0x2d,0x2e,0x2f,0x30,0x31,0x33,0x34,0x38,0x35,0x36,0x37};
    const char *shift="!@#$%^&*()_+{}|:\"?~<>";
    const uint8_t shifted[]={0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x2d,0x2e,0x2f,0x30,0x31,0x33,0x34,0x38,0x35,0x36,0x37};
    const char *p=c>0&&c<128?strchr(plain,(int)c):0;
    if(p) *key=codes[p-plain];
    else if(c>0&&c<128&&(p=strchr(shift,(int)c))) { *key=shifted[p-shift]; *mod=2; }
  }
  return *key!=0;
}
